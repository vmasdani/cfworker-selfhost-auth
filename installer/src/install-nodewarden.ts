// Install or upgrade NodeWarden (third-party, LGPL-3.0) from its pinned upstream commit.
//
//   1. clone the pinned commit into .installer/apps/nodewarden and verify the commit hash
//   2. npm ci --ignore-scripts (no upstream install scripts run)
//   3. resources via cf: D1 nodewarden-db and, for the KV variant, KV nodewarden-attachments-kv;
//      reuse by name or create (asks first)
//   4. write .installer's own Wrangler config into the clone: upstream config + resource IDs,
//      workers_dev = false when a custom domain is used. Upstream's ensure-kv script is not run.
//   5. JWT_SECRET only if missing (via 0600 temp file and --secrets-file; Wrangler keeps others)
//   6. npx wrangler deploy (upstream ships wrangler.toml, so it deploys with Wrangler)
//   7. caller claims the admin account immediately (NodeWarden's first registered user is admin)
// Nothing is ever deleted.

import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { APPS } from "./apps.ts";
import { createD1, createKv, dnsRecordsNamed, findD1, findKv, isWorkerManaged, workerSecretNames, zoneFor, type CfContext } from "./lib/cf.ts";
import { generateSecret } from "./lib/password.ts";
import { waitHealthy } from "./lib/wait.ts";
import { ClaimError } from "./nodewarden.ts";

const ROOT = join(import.meta.dir, "..", "..");
const DIR = join(ROOT, ".installer", "apps", "nodewarden");
const WORKER = "nodewarden";
const DB_NAME = "nodewarden-db";
const KV_TITLE = "nodewarden-attachments-kv";
const R2_BUCKET = "nodewarden-attachments";

export type NodewardenVariant = "kv" | "r2";

export interface NodewardenInstallOptions {
	ctx: CfContext;
	domain?: string;
	variant: NodewardenVariant;
	dryRun: boolean;
	yes: boolean;
	confirm: (q: string) => boolean;
	log: (m: string) => void;
}

async function run(cmd: string[], opts: { cwd?: string; env?: Record<string, string> } = {}) {
	const proc = Bun.spawn(cmd, { cwd: opts.cwd, env: { ...process.env, ...opts.env }, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
	const [stdout, stderr, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited]);
	return { code, stdout, stderr };
}

async function must(cmd: string[], opts: { cwd?: string; env?: Record<string, string> } = {}) {
	const r = await run(cmd, opts);
	if (r.code !== 0) throw new ClaimError(`${cmd.slice(0, 3).join(" ")} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim().split("\n").slice(-6).join(" ").slice(0, 500)}`);
	return r;
}

/** Clone or update the pinned commit, and verify it. */
async function checkout(log: (m: string) => void): Promise<void> {
	const app = APPS.find((a) => a.id === "nodewarden")!;
	if (app.source.kind !== "git") throw new Error("nodewarden source must be git");
	const { repo, commit, tag } = app.source;
	mkdirSync(DIR, { recursive: true });
	if (!existsSync(join(DIR, ".git"))) {
		await must(["git", "init", "-q"], { cwd: DIR });
		await must(["git", "remote", "add", "origin", repo], { cwd: DIR });
	}
	const head = (await run(["git", "rev-parse", "HEAD"], { cwd: DIR })).stdout.trim();
	if (head !== commit) {
		await must(["git", "fetch", "-q", "--depth", "1", "origin", commit], { cwd: DIR });
		await must(["git", "checkout", "-q", "--force", "FETCH_HEAD"], { cwd: DIR });
	}
	const now = (await must(["git", "rev-parse", "HEAD"], { cwd: DIR })).stdout.trim();
	if (now !== commit) throw new ClaimError(`NodeWarden checkout is ${now}, expected pinned ${commit}`);
	const dirty = (await run(["git", "status", "--porcelain", "--untracked-files=no"], { cwd: DIR })).stdout.trim();
	if (dirty) throw new ClaimError(`Upstream files in ${DIR} were modified; refusing to deploy. Delete that folder and re-run.`);
	log(`✓ NodeWarden ${tag} (${commit.slice(0, 12)}), commit verified`);
	await must(["npm", "ci", "--ignore-scripts", "--no-audit", "--no-fund"], { cwd: DIR });
	log("✓ dependencies installed (npm ci, install scripts disabled)");
}

/** Upstream config with our resource IDs and domain settings, as a separate file. */
function writeConfig(variant: NodewardenVariant, ids: { d1?: string; kv?: string }, domain: string | undefined): string {
	let toml = readFileSync(join(DIR, variant === "kv" ? "wrangler.kv.toml" : "wrangler.toml"), "utf8");
	if (ids.d1) toml = toml.replace(/(database_name\s*=\s*"nodewarden-db")/, `$1\ndatabase_id = "${ids.d1}"`);
	if (variant === "kv" && ids.kv) toml = toml.replace(/(binding\s*=\s*"ATTACHMENTS_KV")/, `$1\nid = "${ids.kv}"`);
	const header =
		"# Generated by cfworker-selfhost-auth installer from the upstream config. Do not edit; re-run the installer.\n" +
		(domain ? "workers_dev = false\npreview_urls = false\n" : "");
	const out = join(DIR, "wrangler.installer.toml");
	writeFileSync(out, header + toml);
	return out;
}

export async function installNodewarden(o: NodewardenInstallOptions): Promise<{ url: string | null }> {
	const { ctx, log } = o;
	const existingSecrets = await workerSecretNames(ctx, WORKER);
	const firstInstall = existingSecrets === null;

	if (o.domain) {
		const zone = await zoneFor(ctx, o.domain);
		if (!zone) throw new ClaimError(`No zone for ${o.domain} in this account.`);
		const records = await dnsRecordsNamed(ctx, zone.name, o.domain);
		const foreign = records.filter((r) => !isWorkerManaged(r));
		if (foreign.length) throw new ClaimError(`${o.domain} already has DNS records (${foreign.map((r) => r.type).join(", ")}). Pick another hostname.`);
		if (records.length && firstInstall) throw new ClaimError(`${o.domain} is already the custom domain of another Worker.`);
		log(`✓ domain ${o.domain} (zone ${zone.name})`);
	} else log("• no custom domain: serving on workers.dev");

	if (o.variant === "r2") {
		throw new ClaimError(`The R2 variant is not automated yet. Use --variant kv, or enable R2 and create bucket "${R2_BUCKET}" yourself.`);
	}

	await checkout(log);
	// Wrangler uses its own credentials: `npx wrangler login`, or a CLOUDFLARE_API_TOKEN you created.
	// cf's stored login is never read or passed on.
	const env: Record<string, string> = { CLOUDFLARE_ACCOUNT_ID: ctx.accountId! };
	if (!o.dryRun) {
		const who = await run(["npx", "wrangler", "whoami"], { cwd: DIR, env });
		if (who.code !== 0 || !who.stdout.includes(ctx.accountId!)) {
			throw new ClaimError(
				`Wrangler is not signed in to account ${ctx.accountId}. Run \`npx wrangler login\` with that account ` +
					"(or set CLOUDFLARE_API_TOKEN to a token you created for it), then re-run. Nothing was deployed.",
			);
		}
		log("✓ Wrangler can deploy to this account");
	}

	// resources
	let db = await findD1(ctx, DB_NAME);
	let kv = await findKv(ctx, KV_TITLE);
	if (db) log(`✓ D1 ${DB_NAME} exists (${db.uuid}), reusing it`);
	if (kv) log(`✓ KV ${KV_TITLE} exists (${kv.id}), reusing it`);
	const missing = [!db && `D1 database "${DB_NAME}"`, !kv && `KV namespace "${KV_TITLE}"`].filter(Boolean) as string[];
	if (missing.length) {
		if (o.dryRun) log(`• would create ${missing.join(" and ")}`);
		else {
			if (!o.yes && !o.confirm(`Create ${missing.join(" and ")}?`)) throw new ClaimError("Aborted. Nothing was created.");
			if (!db) {
				db = await createD1(ctx, DB_NAME);
				log(`✓ created D1 ${DB_NAME} (${db.uuid})`);
			}
			if (!kv) {
				kv = await createKv(ctx, KV_TITLE);
				log(`✓ created KV ${KV_TITLE} (${kv.id})`);
			}
		}
	}

	const config = writeConfig(o.variant, { d1: db?.uuid, kv: kv?.id }, o.domain);
	log("✓ wrote wrangler.installer.toml (upstream config + resource IDs)");

	// NodeWarden creates its schema at runtime; no migrations to apply.
	const secrets: Record<string, string> = {};
	if (!existingSecrets?.includes("JWT_SECRET")) secrets.JWT_SECRET = generateSecret(48);
	log(Object.keys(secrets).length ? "✓ secrets to set: JWT_SECRET (value never printed)" : "✓ JWT_SECRET already set; kept");


	const tmp = mkdtempSync(join(tmpdir(), "cfsa-"));
	const file = join(tmp, "secrets.json");
	try {
		writeFileSync(file, JSON.stringify(secrets), { mode: 0o600 });
		const args = ["npx", "wrangler", "deploy", "-c", config, ...(o.domain ? ["--domain", o.domain] : []), ...(o.dryRun ? ["--dry-run"] : [])];
		if (!o.dryRun && Object.keys(secrets).length) args.push("--secrets-file", file);
		log(o.dryRun ? "• building with Wrangler (dry run, nothing uploaded)…" : "• deploying with Wrangler…");
		const r = await run(args, { cwd: DIR, env });
		if (r.code !== 0) throw new ClaimError(`wrangler deploy failed: ${(r.stderr || r.stdout).trim().split("\n").slice(-8).join(" ").slice(0, 600)}`);
		if (o.dryRun) {
			log("✓ dry run OK");
			return { url: null };
		}
		const url = o.domain ? `https://${o.domain}` : (/https:\/\/[a-z0-9.-]+\.workers\.dev/i.exec(r.stdout + r.stderr)?.[0] ?? null);
		if (!url) throw new ClaimError("Deployed, but could not find the Worker URL in Wrangler output.");
		log(`✓ deployed: ${url}`);
		await waitHealthy(url, "/api/web-bootstrap", log);
		return { url };
	} finally {
		rmSync(tmp, { recursive: true, force: true });
	}
}
